uint16_t colorMix(uint16_t a,uint16_t b,int alpha,int total=3) {
 int r=(((a>>11)&31)*alpha+((b>>11)&31)*(total-alpha))/total;
 int g=(((a>>5)&63)*alpha+((b>>5)&63)*(total-alpha))/total;
 int bl=((a&31)*alpha+(b&31)*(total-alpha))/total;
 return (r<<11)|(g<<5)|bl;
}
